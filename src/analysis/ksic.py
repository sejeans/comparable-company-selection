def midclass_code(induty_code) -> str:
    code = str(int(induty_code)).zfill(2)
    return code[:2]


def midclass_name(induty_code) -> str:
    code = midclass_code(induty_code)
    return KSIC_MIDCLASS_NAMES.get(code, f"기타(코드 {code})")
